package io.factry.historian.gateway;

import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.DefaultValue;
import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.Description;
import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.FormCategory;
import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.FormField;
import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.Maximum;
import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.Minimum;
import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.Label;
import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.NonSecret;
import com.inductiveautomation.ignition.gateway.dataroutes.openapi.annotations.Required;
import com.inductiveautomation.ignition.gateway.secrets.SecretConfig;
import com.inductiveautomation.ignition.gateway.web.nav.FormFieldType;

public record FactryHistorianConfig(
        @FormCategory("Connection")
        @Label("Collector Token*")
        @FormField(FormFieldType.SECRET)
        @Required
        @Description("Collector token generated by Factry Historian. Embedded: paste it here; the gateway stores it "
                + "encrypted. Referenced: read it from a secret provider. Connection settings (host, port, "
                + "collector ID) are extracted from it.")
        SecretConfig collectorToken,

        @FormCategory("Connection")
        @Label("Host Override")
        @FormField(FormFieldType.TEXT)
        @DefaultValue("")
        @Description("Optional. The host name or IP address the gateway reaches Factry Historian on, when that is not "
                + "the host in the token (Docker, NAT, another DNS name). Leave empty to use the token's host. A new "
                + "token does not change this value.")
        String hostOverride,

        @FormCategory("Connection")
        @Label("Port Override")
        @FormField(FormFieldType.NUMBER)
        // Ignition's form has no empty number field (a cleared one is refused), so 0 means "not set".
        @DefaultValue("0")
        @Minimum("0")
        @Maximum("65535")
        @Description("Optional. Factry Historian's gRPC port as the gateway reaches it, when that is not the "
                + "grpc-port in the token. 0 (the default) uses the token's port. A new token does not change this value.")
        Integer portOverride,

        // Off by default, as every checkbox here: Ignition's create form shows no defaults
        // (FactryHistorianExtensionPoint.defaultSettings), so a box that defaults to on would look off.
        @FormCategory("Connection")
        @Label("Plain Text (No TLS)")
        @FormField(FormFieldType.CHECKBOX)
        @DefaultValue("false")
        @Description("Connect without TLS. Only for a Factry Historian with its gRPC TLS turned off "
                + "(USE_SELF_SIGNED_CERTIFICATE=false) and nothing in between that ends TLS: the collector token is "
                + "then sent unencrypted. The module uses TLS whatever this says when the token says Factry serves "
                + "its built-in certificate, or when Skip TLS Verification or a Custom CA Certificate is set.")
        boolean plainText,

        @FormCategory("Connection")
        @Label("Skip TLS Verification")
        @FormField(FormFieldType.CHECKBOX)
        @DefaultValue("false")
        @Description("Encrypt the connection without checking Factry's certificate. Anyone who can redirect the "
                + "connection then gets the collector token. Use only for testing.")
        boolean skipTlsVerification,

        @FormCategory("Connection")
        @Label("Custom CA Certificate (PEM)")
        @FormField(FormFieldType.TEXTAREA)
        @DefaultValue("")
        @NonSecret
        @Description("Optional. Not needed for Factry's built-in certificate, which the module checks against "
                + "Factry's own CA. When Factry Historian, or a proxy in front of it, has a certificate of its own from "
                + "an internal CA or a self-signed one, paste that CA (or the self-signed certificate) in PEM here. The "
                + "module then trusts it besides the system CAs, and the certificate must name the host the gateway "
                + "connects to (Host Override, or the token's host). Ignored when 'Skip TLS Verification' is on.")
        String customCaCert,

        @FormCategory("Advanced")
        @Label("Debug Logging")
        @FormField(FormFieldType.CHECKBOX)
        @DefaultValue("false")
        @Description("Enable detailed debug logging.")
        boolean debugLogging,

        @FormCategory("Advanced")
        @Label("Tag Path Delimiter")
        @FormField(FormFieldType.TEXT)
        @DefaultValue("")
        @Description("Character Ignition uses to parse a tag path into a tree view in the Power Chart and tag browser. "
                + "Leave empty (default) to show tags as a flat list (any '/' in the path is preserved with a special character so it is not split). "
                + "Set '/' to split the path into a hierarchical tree. "
                + "Set another character (e.g. '.') to build the tree by splitting on that character instead.")
        String delimiter
) {
    public FactryHistorianSettings toSettings() {
        FactryHistorianSettings settings = new FactryHistorianSettings();
        settings.setCollectorToken(collectorToken);
        settings.setHostOverride(hostOverride);
        settings.setPortOverride(portOverride);
        settings.setPlainText(plainText);
        settings.setSkipTlsVerification(skipTlsVerification);
        settings.setCustomCaCert(customCaCert);
        settings.setDebugLogging(debugLogging);
        settings.setDelimiter(delimiter);
        return settings;
    }

    public static FactryHistorianConfig fromSettings(FactryHistorianSettings settings) {
        return new FactryHistorianConfig(
                settings.getCollectorToken(),
                settings.getHostOverride(),
                settings.getPortOverride(),
                settings.isPlainText(),
                settings.isSkipTlsVerification(),
                settings.getCustomCaCert(),
                settings.isDebugLogging(),
                settings.getDelimiter()
        );
    }
}
